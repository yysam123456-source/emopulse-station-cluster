// 黄金值校验（REUSE-4 / A4 指标，T-R02 第 3 批交付物 ①）。
//
// 目的：证明「移植过来的纯函数」与「原件公式」在 1e-6 内一致——不是「跑一遍看它自己输出啥」。
//
// 防自证循环（本脚本一半的代码都在干这个）：
//   ① 期望值写在 `tests/golden/<part>.json` 里，**不由实现生成**；
//   ② 每条 case 必须带 `derivation`（非空、≥20 字），且必须是**从公式手算代入的表达式**；
//   ③ `derivation` 里禁止出现自我指涉措辞（「实际输出」「由实现生成」「跑一遍」等）——
//      这类句子等价于「实际输出 = 实际输出」，它永远为真，因此不能证明任何事；
//   ④ 脚本只做 `|actual - expect| <= tol` 的比较，不写回任何期望值。
//
// 适配器（adapter）：golden JSON 只声明「用哪个适配器取函数」，取函数的方式写在脚本里。
//   为什么不在 JSON 里写加载路径：JSON 是**期望值清单**，不该承载加载逻辑；
//   但适配器也**不允许硬编码算法清单**——算法清单的唯一来源是 docs §7.x（门 9 负责）。
//
// 已注册适配器：见 `tests/lib/part-adapters.mjs`（与 mutation-probe 共用）。
// 共用的理由：黄金值验的是「函数 A」，探针探的是「函数 B」，若两处各自加载，就可能出现
// 「验 A 探 B」—— 两条门都绿，但声称移植的那个函数一次都没被验过。
//
// 用法：node tests/golden-run.mjs [--report]
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { loadTsModule, REPO_ROOT } from './lib/load-ts.mjs';
import { ADAPTERS, LIB, loadAdapter } from './lib/part-adapters.mjs';

/** golden 清单目录。 */
const GOLDEN_DIR = path.join(REPO_ROOT, 'tests', 'golden');
/** derivation 最少字数。 */
const MIN_DERIVATION_LENGTH = 20;
/** 自我指涉措辞（出现即视为自证循环）。 */
const SELF_REFERENCE = /实际输出|由实现生成|computed by impl|generated by impl|跑一遍就看|以实际为准/i;

const failures = [];
let checks = 0;

/**
 * 记一次断言。
 * @param {boolean} condition 断言结果
 * @param {string} message 失败描述
 * @returns {boolean} 原样返回
 */
function check(condition, message) {
  checks += 1;
  if (!condition) failures.push(message);
  return condition;
}

/**
 * 数值/字符串/数组比较。
 * @param {unknown} actual 实际值
 * @param {unknown} expect 期望值
 * @param {number} tol 容差
 * @returns {string|null} 不匹配时的说明；匹配返回 null
 */
function compareValue(actual, expect, tol) {
  if (Array.isArray(expect)) {
    if (!Array.isArray(actual) || actual.length !== expect.length) {
      return `期望数组长度 ${expect.length}，实际 ${Array.isArray(actual) ? actual.length : typeof actual}`;
    }
    for (let index = 0; index < expect.length; index += 1) {
      const detail = compareValue(actual[index], expect[index], tol);
      if (detail) return `[${index}] ${detail}`;
    }
    return null;
  }
  if (typeof expect === 'number') {
    if (typeof actual !== 'number' || !Number.isFinite(actual)) return `期望数值，实际 ${String(actual)}`;
    const delta = Math.abs(actual - expect);
    return delta <= tol ? null : `期望 ${expect}，实际 ${actual}（差 ${delta.toExponential(3)} > ${tol}）`;
  }
  return actual === expect ? null : `期望 ${JSON.stringify(expect)}，实际 ${JSON.stringify(actual)}`;
}

/**
 * 校验 derivation 字段（防自证循环的核心）。
 * @param {unknown} derivation 代入过程
 * @param {string} label 用例标签
 * @returns {string[]} 问题列表
 */
function derivationProblems(derivation, label) {
  const problems = [];
  if (typeof derivation !== 'string' || derivation.trim() === '') {
    problems.push(`${label} 缺 derivation`);
    return problems;
  }
  const text = derivation.trim();
  if (text.length < MIN_DERIVATION_LENGTH) problems.push(`${label} 的 derivation 只有 ${text.length} 字（<${MIN_DERIVATION_LENGTH}）`);
  if (SELF_REFERENCE.test(text)) problems.push(`${label} 的 derivation 出现自我指涉措辞（自证循环）`);
  if (!text.includes('=')) problems.push(`${label} 的 derivation 不含任何「=」（不是代入过程，是描述）`);
  if (!/\d/.test(text)) problems.push(`${label} 的 derivation 不含任何数字（无法核对代入）`);
  return problems;
}

/** 主流程。 */
async function main() {
  if (!existsSync(GOLDEN_DIR)) {
    console.log(`[golden-run] ❌ 找不到 golden 目录：${path.relative(REPO_ROOT, GOLDEN_DIR)}`);
    process.exitCode = 1;
    return;
  }
  const files = readdirSync(GOLDEN_DIR).filter((name) => name.endsWith('.json')).sort();
  console.log(`[golden-run] 黄金值校验（容差默认 1e-6；期望值来自 tests/golden/*.json 的手算 derivation）`);
  console.log(`  清单 ${files.length} 份：${files.join(', ')}`);

  // ---------- 覆盖面：登记了就必须有 golden，不许静默跳过 ----------
  // 与门 9 同一纪律：**缺清单不许当通过**。原先本脚本只遍历 tests/golden/*.json，
  // 于是「登记了但没写 golden」的零件根本不会出现在这里 —— 那不是通过，是没看见。
  // 需要 golden 的判据：depth 为 D3（真移植，必须有黄金值对账）或 ported 非空（有移植符号）。
  const knownIds = new Set(files.map((name) => path.basename(name, '.json')));
  let registry = null;
  try {
    registry = await loadTsModule(path.join(LIB, 'registry', 'index.ts'));
  } catch (error) {
    check(false, `registry/index.ts 装载失败，无法核对 golden 覆盖面：${String(error.message).split('\n')[0]}`);
  }
  const manifests = Array.isArray(registry?.PART_MANIFESTS) ? registry.PART_MANIFESTS : [];
  const missing = [];
  for (const manifest of manifests) {
    const depth = String(manifest?.provenance?.depth ?? '');
    const ported = Array.isArray(manifest?.provenance?.ported) ? manifest.provenance.ported : [];
    const needsGolden = depth === 'D3' || ported.length > 0;
    if (needsGolden && !knownIds.has(String(manifest.id))) missing.push(`${manifest.id}（depth=${depth}, ported=${ported.length}）`);
  }
  check(
    missing.length === 0,
    `以下零件已登记且需要 golden，但缺 tests/golden/<id>.json：${missing.join('、')}（缺清单不许当通过）`,
  );
  if (missing.length === 0) console.log(`  覆盖面：${manifests.length} 件已登记零件中，需要 golden 的均有清单`);

  const summary = [];
  for (const file of files) {
    const raw = readFileSync(path.join(GOLDEN_DIR, file), 'utf8');
    let spec;
    try {
      spec = JSON.parse(raw);
    } catch (error) {
      check(false, `${file} 不是合法 JSON：${error.message}`);
      continue;
    }
    const part = String(spec.part ?? path.basename(file, '.json'));
    const adapterName = String(spec.adapter ?? '');
    if (!Object.hasOwn(ADAPTERS, adapterName)) {
      check(false, `${part} 的 adapter 未注册：${adapterName || '(空)'}（已注册：${Object.keys(ADAPTERS).join(', ')}）`);
      continue;
    }
    let ns;
    try {
      ns = await loadAdapter(adapterName);
    } catch (error) {
      check(false, `${part} 适配器 ${adapterName} 加载失败：${String(error.message).split('\n')[0]}`);
      continue;
    }

    const cases = Array.isArray(spec.cases) ? spec.cases : [];
    check(cases.length > 0, `${part} 的 cases 为空（没有黄金值就等于没验）`);
    let passed = 0;
    const caseProblems = [];
    for (const item of cases) {
      const symbol = String(item?.symbol ?? '');
      const label = `${part}.${symbol}(${JSON.stringify(item?.args ?? [])})`;
      const tol = typeof item?.tol === 'number' ? item.tol : 1e-6;

      for (const problem of derivationProblems(item?.derivation, label)) caseProblems.push(problem);

      const fn = ns[symbol];
      if (typeof fn !== 'function') {
        caseProblems.push(`${label} 在适配器命名空间里不是函数（symbol 拼错或适配器抽错）`);
        continue;
      }
      let actual;
      try {
        actual = fn(...(Array.isArray(item.args) ? item.args : []));
      } catch (error) {
        caseProblems.push(`${label} 调用抛错：${String(error.message).split('\n')[0]}`);
        continue;
      }
      // 字符串 / 枚举类必须 tol=0，否则「带容差的字符串比较」会变成永远为真的橡皮尺
      if (typeof item.expect === 'string' && tol !== 0) {
        caseProblems.push(`${label} 的 expect 是字符串，tol 必须为 0（实际 ${tol}）`);
      }
      const mismatch = compareValue(actual, item.expect, tol);
      if (mismatch) caseProblems.push(`${label} ${mismatch}`);
      else passed += 1;
    }

    check(caseProblems.length === 0, `${part}：${caseProblems.slice(0, 6).join('；')}${caseProblems.length > 6 ? `…（共 ${caseProblems.length} 条）` : ''}`);
    summary.push({ part, adapter: adapterName, cases: cases.length, passed, problems: caseProblems });
  }

  console.log('');
  console.log('  零件              适配器                    用例  通过  结果');
  for (const row of summary) {
    console.log(`  ${row.part.padEnd(17)} ${row.adapter.padEnd(24)} ${String(row.cases).padStart(4)} ${String(row.passed).padStart(5)}  ${row.problems.length === 0 ? '✓' : '✗'}`);
  }
  const totalCases = summary.reduce((sum, row) => sum + row.cases, 0);
  const totalPassed = summary.reduce((sum, row) => sum + row.passed, 0);
  const passRate = totalCases === 0 ? 0 : totalPassed / totalCases;
  console.log('');
  console.log(`[golden-run] 通过率 ${(passRate * 100).toFixed(1)}%（${totalPassed}/${totalCases}）——门要求必须 = 100%`);
  check(passRate === 1, `黄金值通过率 ${(passRate * 100).toFixed(1)}% ≠ 100%`);

  if (process.argv.includes('--report')) {
    console.log(`[golden-run] （--report）本次结果：${JSON.stringify(summary)}`);
  }

  if (failures.length > 0) {
    console.log('');
    console.log(`[golden-run] ❌ FAIL：${failures.length} 项失败（断言 ${checks} 项）`);
    for (const failure of failures) console.log(`  - ${failure}`);
    process.exitCode = 1;
    return;
  }
  console.log('');
  console.log(`[golden-run] ✅ PASS：${checks} 项断言（${totalCases} 条黄金值全部在容差内，derivation 全部可核对）`);
}

await main();
